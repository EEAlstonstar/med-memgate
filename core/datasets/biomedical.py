"""
Biomedical dataset loader for TierMem.

Loads sessions.jsonl generated by scripts/biomedical/1_convert_to_sessions.py.
Each session simulates a multi-visit doctor-patient scenario:
  - turns      : fine-grained (Patient/Doctor exchange per visit)
  - session_chunks : coarse-grained (one block per visit)
  - qa_pairs   : 1-3 queries per session testing complete/temporal recall

QA categories:
  0 = complete  (list all entities across all visits) → expected route: R
  1 = first_visit (entities from first visit only)   → expected route: R
  2 = latest      (entities from most recent visit)  → expected route: S
"""

import json
from pathlib import Path
from typing import Any, Dict, Iterator, Optional


def iter_sessions(
    data_path: Optional[str] = None,
    split: str = "test",
    limit: Optional[int] = None,
) -> Iterator[Dict[str, Any]]:
    """Yield TierMem-format sessions from biomedical sessions.jsonl.

    Args:
        data_path: Path to sessions.jsonl. Defaults to
                   core/datasets/biomedical/sessions.jsonl relative to cwd.
        split:     Ignored (single split available); kept for interface parity.
        limit:     If given, yield at most this many sessions.
    """
    if data_path is None:
        data_path = str(Path("core/datasets/biomedical/sessions.jsonl"))

    path = Path(data_path)
    if not path.exists():
        raise FileNotFoundError(
            f"Biomedical sessions file not found: {path}\n"
            "Run scripts/biomedical/1_convert_to_sessions.py first."
        )

    count = 0
    with open(path, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            session = json.loads(line)
            yield _normalise(session)
            count += 1
            if limit is not None and count >= limit:
                break


def _normalise(session: Dict[str, Any]) -> Dict[str, Any]:
    """Ensure the session conforms to the TierMem session interface."""
    # Guarantee required top-level keys
    session.setdefault("turns", [])
    session.setdefault("session_chunks", [])
    session.setdefault("qa_pairs", [])
    session.setdefault("meta", {})

    # Normalise turns: ensure speaker/text/timestamp/dia_id
    for t in session["turns"]:
        t.setdefault("speaker", "user")
        t.setdefault("text", "")
        t.setdefault("timestamp", None)
        t.setdefault("dia_id", "")

    # Normalise qa_pairs: ensure all required fields
    for qa in session["qa_pairs"]:
        qa.setdefault("query_id", f"{session['session_id']}_q?")
        qa.setdefault("question", "")
        # ground_truth may be a string; keep as-is (scorer handles both str and list)
        qa.setdefault("ground_truth", "")
        qa.setdefault("category", 0)
        qa.setdefault("meta", {})

    return session
